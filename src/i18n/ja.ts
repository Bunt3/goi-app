/** Japanese strings already produced, so a translated node is not looked up again. */
const VALUES = new Set(Object.values(JA));

/** The Japanese for an English interface string, or null if there is none. */
export function translate(en: string): string | null {
  const exact = JA[en];
  if (exact !== undefined) return exact;
  if (VALUES.has(en)) return null;
  for (const [re, fn] of PATTERNS) {
    const m = en.match(re);
    if (m) return fn(m);
  }
  return null;
}
