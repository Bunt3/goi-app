const UNIT: Record<string, string> = { m: '分', h: '時間', d: '日', mo: 'か月', y: '年' };

/** "today", "yesterday", "3 days ago", "never" as written by daysAgoText. */
function ago(s: string): string {
  if (s === 'today') return '今日';
  if (s === 'yesterday') return '昨日';
  if (s === 'never') return 'まだ一度も';
  const m = s.match(/^(\d+) days ago$/);
  return m ? `${m[1]}日前` : s;
}

